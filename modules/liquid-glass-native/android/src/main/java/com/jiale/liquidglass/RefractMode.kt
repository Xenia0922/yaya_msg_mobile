package com.jiale.liquidglass

/**
 * 折射（透镜感）的两种做法。**两套都留着，可以对着比** —— 这不是冗余代码：
 * 它们的成本差一个数量级，观感也不同，适合不同的控件。
 *
 * [SCALE]「整体放大」：整块背板以控件中心为轴等比放大，位移 = (s−1)·r，**线性**——
 * 中场就已经动掉一半，而且长边的位移天然大于短边。**只花 1 次绘制**，是最省的那档。
 *
 * [FIELD]「边缘折射」：图层不缩放，改成把背板**逐层内缩**着画，每环一个采样位移；
 * 内圈严格不动、位移集中在轮廓附近，沿带用 `smoothstep` 衰减到 0。
 * 位移按两个方向分别折算（÷ 半宽 / 半高），所以**长边短边的位移量一致**。
 * 代价是每个环一次带裁剪的绘制（环数 3–6，自适应）。
 *
 * 两者**共用同一个强度参数** [GlassParams.refractDp]（单位是"轮廓处的位移量 dp"），
 * 所以同样数值下 [FIELD] 看起来更弱——它的位移是从 0 起算的。
 */
enum class RefractMode(val label: String, val description: String) {
    SCALE("整体放大", "整块等比放大：位移线性、长边比短边大。最省（1 次绘制）"),
    FIELD("边缘折射", "只折贴边一条带、逐层内缩：位移集中在边缘，中心不动"),
}
